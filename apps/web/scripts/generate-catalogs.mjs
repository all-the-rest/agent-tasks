#!/usr/bin/env node
/**
 * Catalogs for the UI.
 *
 * The typed dictionaries (`src/i18n/en.ts`, `src/i18n/de.ts`) stay the authoring
 * source: TypeScript proves that German has exactly the English shape. This script
 * flattens them into
 *
 *   - gettext PO files under `src/locales/<locale>/messages.po` for translators, and
 *   - compiled catalogs under `src/locales/<locale>/messages.ts` for @lingui/core.
 *
 * Message ids are the stable dot keys (`tasks.nextRun`), so a translation survives a
 * copy change in English.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function flatten(value, prefix = '', out = {}) {
  for (const [key, entry] of Object.entries(value)) {
    const id = prefix ? `${prefix}.${key}` : key;
    if (typeof entry === 'string') out[id] = entry;
    else flatten(entry, id, out);
  }
  return out;
}

const { en } = await import(join(root, 'src/i18n/en.ts'));
const { de } = await import(join(root, 'src/i18n/de.ts'));

const catalogs = { en: flatten(en.translation), de: flatten(de.translation) };
const englishKeys = Object.keys(catalogs.en).sort();
const germanKeys = Object.keys(catalogs.de).sort();
if (englishKeys.join('\n') !== germanKeys.join('\n')) {
  console.error('catalogs diverge — German must translate exactly the English keys');
  process.exit(1);
}

for (const [locale, messages] of Object.entries(catalogs)) {
  const dir = join(root, 'src/locales', locale);
  mkdirSync(dir, { recursive: true });

  const entries = englishKeys.map((id) => ({ id, message: messages[id] }));
  writeFileSync(join(dir, 'messages.ts'), `// generated by scripts/generate-catalogs.mjs — do not edit\nexport const messages: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries.map((entry) => [entry.id, entry.message])), null, 2)};\n`);

  const po = [
    'msgid ""',
    'msgstr ""',
    '"Content-Type: text/plain; charset=utf-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    '"Language: ' + locale + '\\n"',
    '',
    ...englishKeys.flatMap((id) => [`msgid "${id}"`, `msgstr "${messages[id].replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`, '']),
  ].join('\n');
  writeFileSync(join(dir, 'messages.po'), po);
}

console.log(`wrote ${englishKeys.length} messages for ${Object.keys(catalogs).join(', ')}`);
